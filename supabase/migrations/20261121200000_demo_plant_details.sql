-- Demo plant details (scripts/demo-plant-details/fill.mjs and remove.mjs).
--
-- fill.mjs fills EMPTY plant detail fields with plausible demo values, and remove.mjs takes
-- exactly those values out again. What was generated is recorded here, hidden from people:
--   plants.demo_values      - the plant columns the script filled and the values it wrote,
--                             e.g. {"morphology": "...", "location_description": "..."};
--                             NULL for plants it never touched.
--   observations.is_demo    - true for the one approved observation the script adds to a
--                             plant (for height, diameter, health and life stage), dated
--                             before the day it ran. Approved, so it never enters the
--                             Review queue.
-- Neither column is selected by the web or app screens.
--
-- The scripts run locally with the service-role key (never in the backend). They may write
-- only what they need; RLS and grants for every other role are unchanged.

ALTER TABLE public.plants
    ADD COLUMN IF NOT EXISTS demo_values jsonb;

ALTER TABLE public.observations
    ADD COLUMN IF NOT EXISTS is_demo boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.plants.demo_values IS
    'Plant detail values generated by scripts/demo-plant-details/fill.mjs (field -> value); removed by remove.mjs. Not shown in the UI.';
COMMENT ON COLUMN public.observations.is_demo IS
    'True for demo observations generated by scripts/demo-plant-details/fill.mjs; removed by remove.mjs. Not shown in the UI.';

CREATE INDEX IF NOT EXISTS observations_is_demo_idx
    ON public.observations (plant_id)
    WHERE is_demo;

-- Plants: read (already granted) and write only the generated columns.
GRANT UPDATE (location_description, morphology, description, demo_values)
    ON TABLE public.plants TO service_role;
-- Observations: read existing ones, add the demo one, and delete demo ones on removal.
GRANT SELECT, INSERT, DELETE ON TABLE public.observations TO service_role;
-- Species names and families, to choose plausible values.
GRANT SELECT ON TABLE public.taxonomy TO service_role;
